/**
 * sensitivityCalibration.ts — puts the seven sensitivities on one common ruler.
 *
 * ============================================================================
 * THE PROBLEM THIS SOLVES
 * ============================================================================
 * The seven sensitivities are computed from genuinely different kinds of statistic:
 *
 *   LEVELS      gain responsiveness, outcome aggregation
 *               "how low is your bar?" — a position on a ladder
 *   DIFFERENCES vulnerability protection, group size, directness
 *               "how much further did you move for one case than another?"
 *   VARIATION   context
 *               "how much did your answer change across three settings?"
 *   COMPOSITE   stakeholder shift
 *
 * All seven were then divided by their ladder length and called a 0-100 score, as if that
 * made them comparable. It does not. A level naturally lands near the middle of its range; a
 * difference between two answers on the same ladder is usually small. Measured on a RANDOM
 * responder — someone with no preferences at all — the raw scores came out:
 *
 *      stakeholder 63 · context 56 · outcome 50 · gain 50 · directness 37 · vuln 15 · group 13
 *
 * Block 5 then RANKS these seven against each other to decide a participant's leading value,
 * and weights them against option fingerprints. Ranking a level against a difference is like
 * asking whether someone's height is bigger than their age: the arithmetic works, the answer
 * is meaningless. In practice the two level-type dimensions won almost every time, and the
 * CVR fired on only two of the four policy values — vulnerability protection, the center of
 * the whole thesis, fired 0% of the time.
 *
 * ============================================================================
 * THE FIX: POSITION WITHIN THE INSTRUMENT'S OWN RESPONSE SPACE
 * ============================================================================
 * Every sensitivity is re-expressed as one thing, with one meaning:
 *
 *      "the percentage of all the ways a person could answer this instrument
 *       that this participant's answers exceed on this value"
 *
 * That definition is identical for all seven, so they become directly comparable. It is also
 * a monotone relabeling: it never changes the order of two participants on the same
 * dimension, only the number attached to that order.
 *
 * WHY THIS REFERENCE, AND NOT A POPULATION
 * The tables below describe the INSTRUMENT, not people. They answer "what range of scores can
 * these questions produce, and how often?", which is a fact about the questionnaire that can
 * be recomputed by anyone from the code. No pilot data is required and no assumption about
 * participants is smuggled in — a uniform draw over the response space is the maximum-entropy
 * choice, i.e. the one that assumes least. This matters for defensibility: the scale is a
 * property of the design, fixed before any participant is recruited.
 *
 * WHY "STRICTLY EXCEEDS" AND NOT MID-RANK
 * The percentage counts response patterns STRICTLY below the participant. That guarantees a
 * raw score of zero maps to zero on every dimension, which is essential: three of the seven
 * are clamped at zero when the effect runs the wrong way, and "this factor did not move me"
 * must not be rewarded. The standard mid-rank convention would map a raw zero on group size to
 * 28/100 purely because many response patterns tie there. The cost of this choice is that the
 * highest attainable raw value maps near, rather than exactly to, 100 on some dimensions,
 * because the patterns tying at the top are not counted as exceeded. Since 24 September 2026
 * that cost is removed by dividing by each value's own ceiling - see calibrateSensitivity.
 *
 * ============================================================================
 * REGENERATING THE TABLES
 * ============================================================================
 * Since 24 September 2026 the tables live in sensitivityCalibrationTables.ts, GENERATED by a
 * committed recipe: tools/regenerate_sensitivity_calibration.cjs. It scores 200,000 pretend
 * participants who answer everything by chance - every answer and every button equally likely,
 * seed 20260924 - with the real raw formulas (`rawSensitivityScores` in thresholdTree.ts). Each
 * entry is `[rawScore, percentOfDrawsStrictlyBelowIt]`.
 *
 * WHY IT WAS REBUILT. The first tables (23 August 2026) came from a recipe that was never
 * committed - the procedure file named here did not exist - so they could not be rebuilt when the
 * formulas changed on 24 September, and a reconstruction could not match them. They were replaced
 * whole, all seven at once, by tables this repository can reproduce.
 *
 * They MUST be regenerated whenever anything upstream changes the shape of a raw score: a ladder
 * gains or loses a rung, a signal weight changes, a formula changes, or a block is added. That is
 * now enforced: `npm run calibration:check` (validate:profile, gate K1) fails when the committed
 * tables are not what the recipe produces. Fix it with `npm run calibration:regenerate`.
 */

import { GENERATED_NULL_CDF } from "./sensitivityCalibrationTables";

/**
 * The seven dimension keys, matching `ThresholdTreeDimension.key` in thresholdTree.ts.
 * Declared here rather than imported because that field is typed as a plain `string`;
 * spelling them out gives the calibration table exhaustiveness checking.
 */
export type SensitivityKey =
  | "vulnerability_protection"
  | "group_size"
  | "gain_responsiveness"
  | "outcome_aggregation"
  | "directness"
  | "context"
  | "stakeholder_shift";

/**
 * Identifies the calibration tables in force. Stamped onto every stored participant record, so
 * analysis can tell which scores are comparable with which: two participants scored under
 * different table versions are NOT on the same ruler.
 *
 * Bump this whenever the tables below are regenerated.
 */
/*
 * SINCE 24 SEPTEMBER 2026 THIS NAMES THE WHOLE SCORING RULE SET, not only the tables: the tables, the
 * ceiling division, the tie rule in thresholdTree.ts, and the refusal rule. It is the one stamp an
 * analyst has to check, so any change to any of those moves it. History: Generated
 * Outputs/HOW_TO_READ_MY_DATABASE.md section 6h.
 */
export const SENSITIVITY_CALIBRATION_VERSION = "null-cdf-2026-09-24-recipe-donation-share";

/*
 * HISTORY. "null-cdf-2026-08-23" was the original ruler; four rule changes on 24 September 2026 each
 * got their own label ("…-top100", "…-fair-ties", "…-refusals", "…-halfstep", "…-dc") while the
 * original tables were kept; "null-cdf-2026-09-24-recipe" is all of those rules PLUS tables rebuilt
 * by the committed recipe; "…-recipe-donation-share" also makes Block 1's donation signal a share of
 * refusals instead of one click. Details: Generated Outputs/HOW_TO_READ_MY_DATABASE.md section 6h.
 */

/** `[rawScore, percentOfTheResponseSpaceStrictlyBelowThatScore]`, ascending by rawScore. */
type NullCdf = ReadonlyArray<readonly [number, number]>;

/**
 * Empirical distribution of each raw sensitivity score across the instrument's response space.
 * GENERATED by tools/regenerate_sensitivity_calibration.cjs - see the header. Never edit by hand.
 */
export const SENSITIVITY_NULL_CDF: Record<SensitivityKey, NullCdf> =
  GENERATED_NULL_CDF as Record<SensitivityKey, NullCdf>;

/**
 * The share of the response space one raw score strictly exceeds, before any rounding.
 *
 * Values that fall between two tabulated points are interpolated linearly, so the mapping is
 * continuous and strictly order-preserving. Anything at or below the lowest attainable raw
 * score maps to 0; anything at or above the highest maps to that entry's percentage.
 */
function percentExceeded(cdf: NullCdf, rawScore: number): number {
  if (rawScore <= cdf[0][0]) return 0;
  const last = cdf[cdf.length - 1];
  if (rawScore >= last[0]) return last[1];

  for (let i = 1; i < cdf.length; i++) {
    const [hiRaw, hiPct] = cdf[i];
    if (rawScore === hiRaw) return hiPct;
    if (rawScore < hiRaw) {
      const [loRaw, loPct] = cdf[i - 1];
      const span = hiRaw - loRaw;
      const t = span === 0 ? 0 : (rawScore - loRaw) / span;
      return loPct + t * (hiPct - loPct);
    }
  }
  return last[1];
}

/**
 * The most of the response space anybody can exceed on this value: the percentage the strongest
 * attainable answer reaches. 100 on vulnerability, group size and gain; below 100 on the other four,
 * because the answer patterns that tie at the very top are never counted as exceeded.
 */
export function calibrationTop(key: string): number {
  const cdf = SENSITIVITY_NULL_CDF[key as SensitivityKey];
  return cdf && cdf.length ? cdf[cdf.length - 1][1] : 100;
}

/**
 * Converts one raw sensitivity score (0-100) into its position on the common ruler (0-100).
 *
 * EVERY VALUE CAN REACH 100 (24 September 2026, researcher's approval).
 *
 * The share exceeded is divided by the most that anybody CAN exceed on that value, so the strongest
 * possible answer is exactly 100 on all seven. Before this, the ceiling differed by value, because
 * "strictly exceeds" never counts the patterns that tie at the top:
 *
 *     helped (outcome) 98.8 · directness 97.4 · stakeholder 97.3 · context 93.1 · the other three 100
 *
 * That gap decided real rankings. A participant who gave the strongest possible answer on BOTH gain
 * and helped scored 100 against 99, so gain always came first - a property of the table, not of
 * anything they said. It also meant context could never beat directness at the very top when the
 * CVR lens is chosen.
 *
 * WHAT DOES NOT CHANGE. Zero still maps to zero. The order of two participants on the same value
 * never changes (dividing by a constant is monotone). Vulnerability, group size and gain already
 * reached 100, so their numbers are byte-identical to before; only the other four move, and only
 * by their ceiling - at most 7% for context.
 *
 * WHAT THE NUMBER NOW MEANS: the share of the reachable range this participant exceeds on this
 * value, where "reachable" is set by the instrument itself.
 */
export function calibrateSensitivity(key: string, rawScore: number): number {
  const cdf = SENSITIVITY_NULL_CDF[key as SensitivityKey];
  if (!cdf || cdf.length === 0) return Math.round(rawScore);

  const top = calibrationTop(key);
  const pct = percentExceeded(cdf, rawScore);
  return top > 0 ? Math.round((pct * 100) / top) : Math.round(pct);
}
